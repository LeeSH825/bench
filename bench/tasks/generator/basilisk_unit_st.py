@dataclass(frozen=True)
class BasiliskUnitSTConfig:
    """Complete immutable configuration of the first Basilisk UNIT-ST case."""

    num_trajectories: int = 8
    duration_s: float = 0.5
    gyro_rate_hz: int = 20
    star_tracker_rate_hz: int = 5
    master_seed: int = 20260801
    initial_attitude_max_rad: float = 0.8
    angular_rate_max_rad_s: float = 0.2
    gyro_bias_max_rad_s: float = 0.01
    gyro_noise_std_rad_s: float = 5.0e-4
    star_tracker_R_rad2: tuple[tuple[float, float, float], ...] = (
        (2.25e-6, 0.0, 0.0),
        (0.0, 2.25e-6, 0.0),
        (0.0, 0.0, 2.25e-6),
    )
    star_tracker_noise_scale: float = 1.0
    randomize_star_tracker_sign: bool = True
    representative_mass_kg: float = 10.0
    representative_spherical_inertia_kg_m2: float = 7.0
    train_fraction: float = 0.6
    val_fraction: float = 0.2
    test_fraction: float = 0.2
    truth_attitude_seed_namespace: str = "basilisk-truth-attitude"
    truth_rate_seed_namespace: str = "basilisk-truth-rate"
    gyro_bias_seed_namespace: str = "gyro-bias"
    gyro_noise_seed_namespace: str = "gyro-white-noise"
    star_tracker_noise_seed_namespace: str = "star-tracker-tangent-noise"
    star_tracker_sign_seed_namespace: str = "star-tracker-representation-sign"
    split_seed_namespace: str = "trajectory-split"

    def __post_init__(self) -> None:
        if int(self.num_trajectories) != self.num_trajectories or self.num_trajectories < 3:
            raise ValueError("num_trajectories must be an integer of at least three")
        for name in ("gyro_rate_hz", "star_tracker_rate_hz"):
            value = getattr(self, name)
            if int(value) != value or value <= 0:
                raise ValueError(f"{name} must be a positive integer")
        if self.gyro_rate_hz % self.star_tracker_rate_hz != 0:
            raise ValueError("gyro_rate_hz must be an integer multiple of star_tracker_rate_hz")
        steps = float(self.duration_s) * int(self.gyro_rate_hz)
        if not np.isfinite(steps) or self.duration_s <= 0.0:
            raise ValueError("duration_s must be finite and positive")
        if not np.isclose(steps, round(steps), rtol=0.0, atol=1.0e-12):
            raise ValueError("duration_s * gyro_rate_hz must be an integer")
        magnitudes = np.asarray(
            (
                self.initial_attitude_max_rad,
                self.angular_rate_max_rad_s,
                self.gyro_bias_max_rad_s,
                self.gyro_noise_std_rad_s,
                self.star_tracker_noise_scale,
            ),
            dtype=np.float64,
        )
        if not np.all(np.isfinite(magnitudes)) or np.any(magnitudes < 0.0):
            raise ValueError("attitude, rate, bias, and noise magnitudes must be nonnegative")
        if self.initial_attitude_max_rad >= math.pi:
            raise ValueError("initial_attitude_max_rad must be smaller than pi")
        if self.angular_rate_max_rad_s > 0.2:
            raise ValueError("Gate B2 angular_rate_max_rad_s must not exceed 0.2 rad/s")
        if not np.isfinite(self.representative_mass_kg) or self.representative_mass_kg <= 0.0:
            raise ValueError("representative_mass_kg must be finite and positive")
        inertia = self.representative_spherical_inertia_kg_m2
        if not np.isfinite(inertia) or inertia <= 0.0:
            raise ValueError("representative spherical inertia must be finite and positive")
        covariance = np.asarray(self.star_tracker_R_rad2, dtype=np.float64)
        if covariance.shape != (3, 3) or not np.all(np.isfinite(covariance)):
            raise ValueError("star_tracker_R_rad2 must be a finite 3x3 matrix")
        if not np.array_equal(covariance, covariance.T):
            raise ValueError("star_tracker_R_rad2 must be exactly symmetric")
        try:
            np.linalg.cholesky(covariance)
        except np.linalg.LinAlgError as error:
            raise ValueError("star_tracker_R_rad2 must be strictly positive definite") from error
        fractions = np.asarray(
            (self.train_fraction, self.val_fraction, self.test_fraction), dtype=np.float64
        )
        if not np.all(np.isfinite(fractions)) or np.any(fractions <= 0.0):
            raise ValueError("split fractions must be finite and positive")
        if not math.isclose(float(np.sum(fractions)), 1.0, rel_tol=0.0, abs_tol=1.0e-12):
            raise ValueError("split fractions must sum to one")
        namespaces = (
            self.truth_attitude_seed_namespace,
            self.truth_rate_seed_namespace,
            self.gyro_bias_seed_namespace,
            self.gyro_noise_seed_namespace,
            self.star_tracker_noise_seed_namespace,
            self.star_tracker_sign_seed_namespace,
            self.split_seed_namespace,
        )
        if any(not isinstance(item, str) or not item for item in namespaces):
            raise ValueError("seed namespaces must be nonempty strings")
        if len(set(namespaces)) != len(namespaces):
            raise ValueError("seed namespaces must be distinct")

    @property
    def task_step_s(self) -> float:
        return 1.0 / float(self.gyro_rate_hz)


