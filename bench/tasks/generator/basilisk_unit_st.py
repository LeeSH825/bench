def _rodrigues(rotation_vector: np.ndarray) -> np.ndarray:
    angle = float(np.linalg.norm(rotation_vector))
    if angle == 0.0:
        return np.eye(3, dtype=np.float64)
    generator = skew(rotation_vector / angle)
    return (
        np.eye(3, dtype=np.float64)
        + math.sin(angle) * generator
        + (1.0 - math.cos(angle)) * (generator @ generator)
    )


def run_static_frame_proof() -> dict[str, Any]:
    """Execute recorder-backed closed-form, arbitrary, and shadow frame proof."""

    bsk = _require_basilisk()
    rbk = bsk["rbk"]
    cases: list[tuple[str, np.ndarray]] = [("identity", np.zeros(3, dtype=np.float64))]
    for axis_name, axis in zip(("x", "y", "z"), np.eye(3, dtype=np.float64)):
        cases.append((f"+{axis_name}90", axis * (math.pi / 2.0)))
        cases.append((f"-{axis_name}90", axis * (-math.pi / 2.0)))
    rng = np.random.default_rng(20260801)
    for index in range(10):
        axis = rng.normal(size=3)
        axis /= np.linalg.norm(axis)
        cases.append((f"arbitrary-{index:02d}", axis * rng.uniform(-2.4, 2.4)))

    maximum_basis_error = 0.0
    maximum_relation_error = 0.0
    maximum_recorder_error = 0.0
    maximum_inverse_candidate_error = 0.0
    case_results: list[dict[str, Any]] = []
    for name, rotation_vector in cases:
        angle = float(np.linalg.norm(rotation_vector))
        sigma = (
            np.zeros(3, dtype=np.float64)
            if angle == 0.0
            else rotation_vector / angle * math.tan(angle / 4.0)
        )
        q_initial = quat_exp(rotation_vector)
        _time, sigma_recorded, _omega = _simulate_recorder(
            q_initial_NB=q_initial,
            omega_initial_B_rad_s=np.zeros(3, dtype=np.float64),
            duration_s=0.0,
            task_step_s=0.01,
            mass_kg=10.0,
            spherical_inertia_kg_m2=7.0,
        )
        q_candidate = basilisk_sigma_BN_to_q_NB(sigma_recorded[0])
        r_nb = quat_to_dcm(q_candidate)
        c_bn = np.asarray(rbk.MRP2C(sigma_recorded[0]), dtype=np.float64)
        expected = _rodrigues(rotation_vector)
        basis_error = float(np.max(np.abs(r_nb @ np.eye(3) - expected @ np.eye(3))))
        relation_error = float(np.max(np.abs(r_nb - c_bn.T)))
        recorder_error = float(np.max(np.abs(sigma_recorded[0] - sigma)))
        inverse_error = float(np.max(np.abs(c_bn - expected)))
        maximum_basis_error = max(maximum_basis_error, basis_error)
        maximum_relation_error = max(maximum_relation_error, relation_error)
        maximum_recorder_error = max(maximum_recorder_error, recorder_error)
        maximum_inverse_candidate_error = max(maximum_inverse_candidate_error, inverse_error)
        case_results.append(
            {
                "name": name,
                "basis_error": basis_error,
                "relation_error": relation_error,
                "recorder_sigma_error": recorder_error,
            }
        )

    maximum_shadow_dcm_error = 0.0
    minimum_shadow_abs_dot = 1.0
    for _name, rotation_vector in cases[1:]:
        q = quat_exp(rotation_vector)
        sigma = np.asarray(rbk.EP2MRP(q), dtype=np.float64)
        shadow = -sigma / float(sigma @ sigma)
        q_primary = basilisk_sigma_BN_to_q_NB(sigma)
        q_shadow = basilisk_sigma_BN_to_q_NB(shadow)
        maximum_shadow_dcm_error = max(
            maximum_shadow_dcm_error,
            float(np.max(np.abs(quat_to_dcm(q_primary) - quat_to_dcm(q_shadow)))),
        )
        minimum_shadow_abs_dot = min(
            minimum_shadow_abs_dot, abs(float(q_primary @ q_shadow))
        )
    return {
        "case_count": len(cases),
        "arbitrary_case_count": 10,
        "max_basis_error": maximum_basis_error,
        "max_R_NB_minus_C_BN_transpose_error": maximum_relation_error,
        "max_recorder_sigma_error": maximum_recorder_error,
        "max_inverse_candidate_error": maximum_inverse_candidate_error,
        "max_shadow_dcm_error": maximum_shadow_dcm_error,
        "min_shadow_abs_quaternion_dot": minimum_shadow_abs_dot,
        "relation": "R_NB = quat_to_dcm(normalize(MRP2EP(sigma_BN))) = C_BN.T",
        "cases": case_results,
    }


def _attitude_log_error(reference: np.ndarray, actual: np.ndarray) -> float:
    delta = quat_multiply(quat_inverse(reference), actual)
    return float(np.linalg.norm(quat_log(delta)))


def run_dynamic_rate_proof() -> dict[str, Any]:
    """Execute zero/axis/arbitrary body-rate proof on coarse and fine grids."""

    rng = np.random.default_rng(10)
    rates: list[np.ndarray] = [np.zeros(3, dtype=np.float64)]
    for axis in np.eye(3, dtype=np.float64):
        rates.extend((0.2 * axis, -0.2 * axis))
    for _index in range(10):
        vector = rng.normal(size=3)
        vector *= rng.uniform(0.01, 0.2) / np.linalg.norm(vector)
        rates.append(vector)
    initial_quaternions = [quat_exp(rng.normal(size=3) * 0.2) for _ in rates]

    grid_results: dict[str, dict[str, float]] = {}
    for label, step in (("coarse", 0.01), ("fine", 0.005)):
        maximum_attitude_error = 0.0
        maximum_local_rate_error = 0.0
        maximum_recorded_rate_error = 0.0
        maximum_rate_norm_drift = 0.0
        for q_initial, omega_initial in zip(initial_quaternions, rates):
            time_s, q_series, omega_series = simulate_basilisk_truth(
                q_initial,
                omega_initial,
                duration_s=1.0,
                task_step_s=step,
            )
            for index, time_value in enumerate(time_s):
                reference = quat_multiply(q_initial, quat_exp(omega_initial * time_value))
                maximum_attitude_error = max(
                    maximum_attitude_error,
                    _attitude_log_error(reference, q_series[index]),
                )
                if index:
                    increment = quat_multiply(
                        quat_inverse(q_series[index - 1]), q_series[index]
                    )
                    local_rate = quat_log(increment) / (time_s[index] - time_s[index - 1])
                    maximum_local_rate_error = max(
                        maximum_local_rate_error,
                        float(np.max(np.abs(local_rate - omega_series[index - 1]))),
                    )
            maximum_recorded_rate_error = max(
                maximum_recorded_rate_error,
                float(np.max(np.abs(omega_series - omega_initial))),
            )
            rate_norms = np.linalg.norm(omega_series, axis=1)
            maximum_rate_norm_drift = max(
                maximum_rate_norm_drift, float(np.max(np.abs(rate_norms - rate_norms[0])))
            )
        grid_results[label] = {
            "task_step_s": step,
            "max_attitude_log_error_rad": maximum_attitude_error,
            "max_local_rate_increment_error_rad_s": maximum_local_rate_error,
            "max_recorded_rate_component_error_rad_s": maximum_recorded_rate_error,
            "max_rate_norm_drift_rad_s": maximum_rate_norm_drift,
        }
    coarse_error = grid_results["coarse"]["max_attitude_log_error_rad"]
    fine_error = grid_results["fine"]["max_attitude_log_error_rad"]
    return {
        "rate_case_count": len(rates),
        "arbitrary_rate_case_count": 10,
        "duration_s": 1.0,
        "max_rate_norm_rad_s": max(float(np.linalg.norm(item)) for item in rates),
        "coarse": grid_results["coarse"],
        "fine": grid_results["fine"],
        "fine_target_rad": 1.0e-8,
        "fine_not_increased": bool(fine_error <= coarse_error),
        "relation": "q_NB(t+dt) = q_NB(t) otimes Exp_q(omega_BN_B*dt)",
        "omega_semantics": "body-frame angular rate omega_BN_B in rad/s, same sign as Gate A gyro propagation",
    }
